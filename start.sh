#!/bin/sh
# Точка входа для облачного деплоя (Railway и т.п.), где один контейнер делает всё:
# сначала индексируем базу знаний, затем запускаем бота.
# Локально docker-compose переопределяет команды и этот скрипт не используется.
set -e

echo "[start] Индексация базы знаний..."
python -m app.ingest

echo "[start] Запуск бота..."
exec python -m app.bot
